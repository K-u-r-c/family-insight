  0xab: 0x00b1, // ±
  0xac: 0x01a0, // Ơ
  0xad: 0x01af, // Ư
  0xae: 0x02bc, // ʼ
  0xb0: 0x02bb, // ʻ
  0xb1: 0x0142, // ł
  0xb2: 0x00f8, // ø
  0xb3: 0x0111, // đ
  0xb4: 0x00fe, // þ
  0xb5: 0x00e6, // æ
  0xb6: 0x0153, // œ
  0xb7: 0x02ba, // ʺ
  0xb8: 0x0131, // ı
  0xb9: 0x00a3, // £
  0xba: 0x00f0, // ð

  f: ['отец', 'мать'],
  m: ['мать', 'отец'],
  gf: ['дед', 'бабушка'],
  mgm: ['бабушка', 'дед'],
  ggf: ['прадед', 'прабабушка'],
  gggf: ['прапрадед', 'прапрабабушка'],
  son: ['сын', 'дочь'],
  gs: ['внук', 'внучка'],
  ggs: ['правнук', 'правнучка'],
  ad: ['приёмная дочь', 'приёмный сын'],
  br: ['брат', 'сестра'],
  hb: ['единокровный брат', 'единокровная сестра'],
  u: ['дядя', 'тётя'],
  mt: ['тётя', 'дядя'],
  hs: ['неполнородная тётя', 'неполнородный дядя'],
  gu: ['двоюродный дед', 'двоюродная бабушка'],
  nep: ['племянник', 'племянница'],
  gnep: ['внучатый племянник', 'внучатая племянница'],
  c1: ['двоюродный брат', 'двоюродная сестра'],
  mc: ['двоюродный брат', 'двоюродная сестра'],
  c1d: ['двоюродная племянница', 'двоюродный племянник'],
  gu1: ['двоюродный дядя', 'двоюродная тётя'],
